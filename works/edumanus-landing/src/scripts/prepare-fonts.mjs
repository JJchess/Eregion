/** Retain original font bytes; include only Noto's Unicode partitions used by this exhibit. */
import { readFileSync, writeFileSync, cpSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const messages = ['en', 'zh'].map((lang) => readFileSync(resolve(root, `messages/${lang}.json`), 'utf8')).join('');
const codepoints = new Set([...messages].map((char) => char.codePointAt(0)));
const stylesheet = readFileSync(resolve(root, 'node_modules/@fontsource-variable/noto-serif-sc/index.css'), 'utf8');
const blocks = [...stylesheet.matchAll(/@font-face\s*\{[^}]+\}/g)].map((match) => match[0]);
function used(block) {
  const spec = block.match(/unicode-range:\s*([^;]+)/)?.[1];
  if (!spec) return true;
  return spec.split(',').some((range) => {
    const [from, to = from] = range.trim().replace(/^U\+/i, '').split('-').map((part) => Number.parseInt(part, 16));
    return [...codepoints].some((point) => point >= from && point <= to);
  });
}
const selected = blocks.filter(used).map((block) => block.replaceAll('url(./files/', 'url(../node_modules/@fontsource-variable/noto-serif-sc/files/'));
writeFileSync(resolve(root, 'app/noto-subsets.css'), `/* Generated by scripts/prepare-fonts.mjs. Original font files are unmodified. */\n${selected.join('\n\n')}\n`);
for (const [pkg, file] of [
  ['@fontsource-variable/geist', 'Geist-OFL.txt'],
  ['@fontsource-variable/geist-mono', 'Geist-Mono-OFL.txt'],
  ['@fontsource-variable/noto-serif-sc', 'Noto-Serif-SC-OFL.txt'],
  ['@fontsource/enriqueta', 'Enriqueta-OFL.txt'],
]) cpSync(resolve(root, `node_modules/${pkg}/LICENSE`), resolve(root, `font-licenses/${file}`));
console.log(`Noto Serif SC: ${selected.length}/${blocks.length} original Unicode partitions included.`);
